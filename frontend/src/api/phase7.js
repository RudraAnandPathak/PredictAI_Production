// Thin wrappers over the Phase 7 endpoints (registry, reports, exam, intelligence, workspaces, schedules, dashboard, owner operations).
// Every call returns the unwrapped `data`; components never build URLs. Authorisation is decided by the server on every request.
import { queryString } from './workspace.js';

const id = encodeURIComponent;
const LONG = 3 * 60 * 1000;

export const phase7Api = (client) => {
  const data = (promise) => promise.then((r) => r.data);
  const call = (method, path, body, timeoutMs = 60000) => data(client.request(path, { method, body: body ?? undefined, timeoutMs }));
  const get = (path, params) => data(client.request(`${path}${queryString(params)}`, { timeoutMs: 60000 }));
  return {
    dashboard: () => get('/dashboard'),
    registry: {
      models: (params) => get('/registry/models', params),
      model: (modelId) => get(`/registry/models/${id(modelId)}`),
      history: (modelId) => get(`/registry/models/${id(modelId)}/history`),
      register: (projectId, body) => call('POST', `/projects/${id(projectId)}/registry/models`, body),
      version: (versionId) => get(`/registry/versions/${id(versionId)}`),
      verify: (versionId) => call('POST', `/registry/versions/${id(versionId)}/verify`, {}),
      transition: (versionId, to, { confirm = false, reason } = {}) => call('POST', `/registry/versions/${id(versionId)}/transition`, { to, confirm, reason: reason || null }),
      rollback: (modelId, toVersionId, { confirm = false, reason } = {}) => call('POST', `/registry/models/${id(modelId)}/rollback`, { to_version_id: toVersionId, confirm, reason: reason || null }),
      compare: (versionIds) => call('POST', '/registry/compare', { version_ids: versionIds }),
      predict: (versionId, values) => call('POST', `/registry/versions/${id(versionId)}/predict`, { values }, 90000),
      monitoring: (versionId) => get(`/registry/versions/${id(versionId)}/monitoring`),
      driftChecks: (versionId, params) => get(`/registry/versions/${id(versionId)}/monitoring/drift`, params),
      checkDrift: (versionId, assetId, datasetVersionId) => call('POST', `/registry/versions/${id(versionId)}/monitoring/drift`, { asset_id: assetId, ...(datasetVersionId ? { dataset_version_id: datasetVersionId } : {}) }, 120000),
      driftCheck: (checkId) => get(`/monitoring/checks/${id(checkId)}`),
      recordOutcome: (versionId, predictionId, actual) => call('POST', `/registry/versions/${id(versionId)}/monitoring/outcomes`, { prediction_id: predictionId, actual }),
      performance: (versionId) => get(`/registry/versions/${id(versionId)}/monitoring/performance`),
    },
    forecast: (assetId, body) => call('POST', `/assets/${id(assetId)}/forecast`, body, 120000),
    reports: {
      templates: () => get('/reports/templates'),
      list: (params) => get('/reports', params),
      get: (reportId, params) => get(`/reports/${id(reportId)}`, params),
      create: (projectId, body) => call('POST', `/projects/${id(projectId)}/reports`, body, LONG),
      edit: (reportId, baseVersion, ops, note) => call('PATCH', `/reports/${id(reportId)}`, { base_version: baseVersion, ops, note: note || null }),
      remove: (reportId) => call('DELETE', `/reports/${id(reportId)}`),
      versions: (reportId) => get(`/reports/${id(reportId)}/versions`),
      diff: (reportId, a, b) => get(`/reports/${id(reportId)}/diff`, { a, b }),
      exports: (reportId) => get(`/reports/${id(reportId)}/exports`),
      createExport: (reportId, body) => call('POST', `/reports/${id(reportId)}/exports`, body, LONG),
      download: (exportId) => client.download(`/report-exports/${id(exportId)}/download`, { method: 'GET' }),
    },
    exam: {
      subjects: (projectId) => get(`/projects/${id(projectId)}/exam/subjects`),
      createSubject: (projectId, body) => call('POST', `/projects/${id(projectId)}/exam/subjects`, body),
      subject: (subjectId) => get(`/exam/subjects/${id(subjectId)}`),
      addDocument: (subjectId, body) => call('POST', `/exam/subjects/${id(subjectId)}/documents`, body, LONG),
      documents: (subjectId) => get(`/exam/subjects/${id(subjectId)}/documents`),
      curriculum: (subjectId) => get(`/exam/subjects/${id(subjectId)}/curriculum`),
      questions: (subjectId, params) => get(`/exam/subjects/${id(subjectId)}/questions`, params),
      correct: (questionId, body) => call('POST', `/exam/questions/${id(questionId)}/mapping`, body),
      analyse: (subjectId, body) => call('POST', `/exam/subjects/${id(subjectId)}/analyses`, body ?? {}, LONG),
      analyses: (subjectId) => get(`/exam/subjects/${id(subjectId)}/analyses`),
      analysis: (analysisId) => get(`/exam/analyses/${id(analysisId)}`),
      blueprint: (subjectId, spec) => call('POST', `/exam/subjects/${id(subjectId)}/blueprints`, { spec: spec ?? {} }),
      generate: (blueprintId, body) => call('POST', `/exam/blueprints/${id(blueprintId)}/generate`, body ?? {}, LONG),
      assessments: (subjectId) => get(`/exam/subjects/${id(subjectId)}/assessments`),
      assessment: (assessmentId) => get(`/exam/assessments/${id(assessmentId)}`),
      validation: (assessmentId) => get(`/exam/assessments/${id(assessmentId)}/validation`),
      approve: (assessmentId, { confirm = false, acknowledgeWarnings = false } = {}) => call('POST', `/exam/assessments/${id(assessmentId)}/approve`, { confirm, acknowledge_warnings: acknowledgeWarnings }),
      reject: (assessmentId) => call('POST', `/exam/assessments/${id(assessmentId)}/reject`, {}),
      predictionOptions: (subjectId) => get(`/exam/subjects/${id(subjectId)}/prediction-options`),
      predict: (subjectId, body) => call('POST', `/exam/subjects/${id(subjectId)}/predictions`, body ?? {}, LONG),
      predictions: (subjectId) => get(`/exam/subjects/${id(subjectId)}/predictions`),
      prediction: (predictionId) => get(`/exam/predictions/${id(predictionId)}`),
      predictedPaper: (predictionId, body) => call('POST', `/exam/predictions/${id(predictionId)}/paper`, body ?? {}, LONG),
    },
    brain: {
      status: () => get('/brain/status'),
      setupGemini: (body) => call('POST', '/brain/setup/gemini', body, LONG),
      models: () => get('/brain/models'),
      test: () => call('POST', '/brain/test', {}, LONG),
    },
    intelligence: {
      rootCause: (assetId, body) => call('POST', `/assets/${id(assetId)}/intelligence/root-cause`, body, LONG),
      metric: (body) => call('POST', '/intelligence/metric', body, LONG),
      scenario: (body) => call('POST', '/intelligence/scenarios', body, LONG),
      causal: (assetId, body) => call('POST', `/assets/${id(assetId)}/intelligence/causal-candidates`, body, LONG),
      runs: (params) => get('/intelligence/runs', params),
      run: (runId) => get(`/intelligence/runs/${id(runId)}`),
    },
    workspaces: {
      list: () => get('/workspaces'),
      create: (body) => call('POST', '/workspaces', body),
      get: (workspaceId) => get(`/workspaces/${id(workspaceId)}`),
      close: (workspaceId) => call('DELETE', `/workspaces/${id(workspaceId)}`),
      myInvitations: () => get('/workspaces/invitations/mine'),
      respond: (token, accept) => call('POST', '/workspaces/invitations/respond', { token, accept }),
      invite: (workspaceId, email, role) => call('POST', `/workspaces/${id(workspaceId)}/invitations`, { email, role }),
      cancelInvitation: (workspaceId, invitationId) => call('DELETE', `/workspaces/${id(workspaceId)}/invitations/${id(invitationId)}`),
      setMember: (workspaceId, userId, body) => call('PATCH', `/workspaces/${id(workspaceId)}/members/${id(userId)}`, body),
      removeMember: (workspaceId, userId) => call('DELETE', `/workspaces/${id(workspaceId)}/members/${id(userId)}`),
      shares: (workspaceId) => get(`/workspaces/${id(workspaceId)}/shares`),
      share: (workspaceId, body) => call('POST', `/workspaces/${id(workspaceId)}/shares`, body),
      revoke: (grantId) => call('DELETE', `/shares/${id(grantId)}`),
      events: (workspaceId, params) => get(`/workspaces/${id(workspaceId)}/events`, params),
    },
    schedules: {
      adapters: () => get('/schedules/adapters'),
      list: (params) => get('/schedules', params),
      get: (scheduleId) => get(`/schedules/${id(scheduleId)}`),
      create: (reportId, spec) => call('POST', `/reports/${id(reportId)}/schedules`, { spec }),
      action: (scheduleId, action) => call('POST', `/schedules/${id(scheduleId)}/action`, { action }),
      run: (scheduleId, key) => call('POST', `/schedules/${id(scheduleId)}/run`, { idempotency_key: key || null }, LONG),
      runs: (scheduleId) => get(`/schedules/${id(scheduleId)}/runs`),
      retry: (deliveryId) => call('POST', `/schedule-deliveries/${id(deliveryId)}/retry`, {}),
      download: (runId) => client.download(`/schedule-runs/${id(runId)}/download`, { method: 'GET' }),
    },
    ownerOps: {
      overview: () => get('/owner/overview'),
      monitoring: () => get('/owner/monitoring'),
      userSummary: (userId) => get(`/owner/users/${id(userId)}/summary`),
      maintenance: () => get('/owner/maintenance'),
      setMaintenance: (active, notice, confirm) => call('PUT', '/owner/maintenance', { active, notice: notice || null, confirm }),
      quotaPolicy: () => get('/owner/quota-policy'),
      setQuota: (key, value) => call('PUT', `/owner/quota-policy/${id(key)}`, { value }),
      resetQuota: (key) => call('DELETE', `/owner/quota-policy/${id(key)}`),
      events: (params) => get('/owner/events', params),
    },
  };
};
